/** Normaliza um texto para comparação: remove acentos, converte para minúsculas, colapsa espaços */
export function normalizeTopic(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .trim();
}

