/**
 * Verifica se um tópico é válido para a disciplina fornecida.
 * A comparação é normalizada: ignora acentos, maiúsculas/minúsculas e espaços extra.
 * @returns O nome oficial do tópico se encontrado, null se não encontrado
 */
export function findValidTopic(subject: string, topic: string): string | null {
  const subjectTopics = MINED_CURRICULUM[subject];
  if (!subjectTopics) {
    // Disciplina não registada na base — aceitar qualquer tópico
    return topic;
  }

  const normalized = normalizeTopic(topic);
  const match = subjectTopics.find(t => normalizeTopic(t) === normalized);
  return match || null;
}

/**
 * Valida uma lista de tópicos para a disciplina dada.
 * @returns Objeto com os tópicos aceites e os tópicos rejeitados
 */
export function validateTopics(subject: string, topics: string[]): {
  valid: string[];
  invalid: string[];
} {
  const valid: string[] = [];
  const invalid: string[] = [];

  for (const topic of topics) {
    const found = findValidTopic(subject, topic);
    if (found !== null) {
      valid.push(found); // usa o nome oficial do MINED
    } else {
      invalid.push(topic);
    }
  }

  return { valid, invalid };
}

/**
 * Retorna todos os tópicos válidos para uma disciplina,
 * ou null se a disciplina não estiver registada.
 */
export function getCurriculumForSubject(subject: string): string[] | null {
  return MINED_CURRICULUM[subject] || null;
}
